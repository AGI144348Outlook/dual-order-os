"""Five bounded passes of actual preserved Genesis indexing and expression.
No LLM, source edits, autonomous choices, ethical-rule promotion or model training.
"""
import argparse
import collections
import hashlib
import json
import re
import sys
import tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from libraries.echo_workspace import genesis
from libraries.echo_sentence_cards import lexicon_from_zip
from libraries.catalog_box import CatalogBox
SOURCE=ROOT/'libraries/research-papers/ethics-governance/consent-paradox/RP-0001_CONSENT_PARADOX.md'
BLOB='86f8e0e6ad0dd4e7ef17c26f5f42eb12077748a3'
def checked_text():
    b=SOURCE.read_bytes()
    if hashlib.sha1(b'blob '+str(len(b)).encode()+b'\0'+b).hexdigest()!=BLOB:raise ValueError('Reading source differs')
    return b.decode()
def topology(lobby):
    return sorted((a,sorted(b.ties)) for a,b in lobby.agents.items())
def reading(lexicon,passes=5):
    if type(passes) is not int or not 1<=passes<=5:raise ValueError('Pass budget 1..5')
    text=checked_text();e=genesis();matrix=e.AlgorithmMatrix();identity=e.ReshIdentity(matrix);identity.anchor()
    for word,entry in lexicon.items():matrix.index_dictionary_entry(word,entry['desc'],entry['pos'])
    tokens=sorted(set(e.AlgorithmicCommunicator()._tokenize(text)))
    def view():
        lobby=e.Lobby(matrix);lobby.populate();lobby.run_orientation();lobby.run_typed_study_groups();lobby.compute_generality_scores()
        return lobby
    lobby=view();original_topology=topology(lobby);original_agents=set(lobby.agents)
    previous_response=None;steps=[]
    def stats(lobby):
        gaps=[t for t in tokens if t not in lobby.agents]
        return {'documents_seen':matrix.documents_seen,'indexed_units':len(matrix.content_units),
            'word_agents':len(lobby.agents),'ties':len(lobby.ties),'known_source_tokens':len(tokens)-len(gaps),
            'gap_tokens':gaps,'source_token_document_counts':{t:matrix.content_units.get(t,0) for t in tokens}}
    baseline=stats(lobby)
    for n in range(1,passes+1):
        # Explicit source exposure, not dictionary-definition fabrication.
        matrix.index_content(text,category='reading:RP-0001')
        lobby=view()
        if not identity.validate():raise RuntimeError('Preserved identity check failed')
        comm=e.AlgorithmicCommunicator(lobby=lobby,vgm={},lexicon=lexicon,alg_matrix=matrix.known)
        response=comm.communicate(text)
        current_topology=topology(lobby)
        steps.append({'pass':n,**stats(lobby),'response':response,
            'response_sha256':hashlib.sha256(response.encode()).hexdigest(),
            'same_response_as_previous':None if previous_response is None else response==previous_response,
            'topology_equal_to_baseline':current_topology==original_topology,
            'new_word_agents':sorted(set(lobby.agents)-original_agents),
            'vgm_statements_supplied':0,'identity_valid':True})
        previous_response=response
    return {'source_git_blob':BLOB,'passes_requested':passes,'baseline':baseline,'passes':steps,
        'unique_content_tokens':len(tokens),'reading_input':'entire unchanged registry abstract/propositions/assessment',
        'execution':'index_content -> Lobby rebuild/orientation -> AlgorithmicCommunicator.communicate',
        'dictionary_projection':'first listed sense per spelling; alternatives not represented by legacy Lobby',
        'interpretation_limits':['No full original essay was found on the requested branch.',
            'Repeated exposure to one source is not independent corroboration.',
            'The preserved Lobby reconstructs definitions from transition targets; prose ingestion may therefore mix context with dictionary-derived links.',
            'No automatic vocabulary definitions, VGM truths, governing rules or consciousness claims are acquired.',
            'Responses are preserved algorithmic output, not a human-readable comprehension summary generated by another model.']}
def main():
    p=argparse.ArgumentParser();p.add_argument('--archive',required=True);p.add_argument('--output',default='reports/echo-consent-reading');args=p.parse_args()
    raw=lexicon_from_zip(args.archive);lexicon={w:{'desc':v['senses'][0]['def'],'pos':v['senses'][0]['pos']} for w,v in raw.items()}
    result=reading(lexicon);out=Path(args.output);out.mkdir(parents=True,exist_ok=True)
    # Persist exposure/observation cards in a separate catalog. Recorder is not a self-directed Echo action.
    with tempfile.TemporaryDirectory() as d:
        db=Path(d)/'observations.sqlite';box=CatalogBox(db)
        box.put_card('source:RP-0001','Consent Paradox reading source',{'kind':'reading-source','git_blob':BLOB,'text':checked_text()},provenance={'source_branch':'code-library-registry'})
        for step in result['passes']:
            box.put_card('read:'+str(step['pass']),'Reading pass '+str(step['pass']),{'kind':'reading-observation',**step},provenance={'source_git_blob':BLOB,'recorded_by':'explicit observation adapter'})
        before=box.list('cards');box.close();box=CatalogBox(db);result['observation_cards_restored']=box.list('cards')==before;box.close()
    for step in result['passes']:
        (out/('pass-'+str(step['pass'])+'.txt')).write_text(step['response'])
    (out/'results.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'passes':len(result['passes']),'source_tokens':result['unique_content_tokens'],
        'baseline_known':result['baseline']['known_source_tokens'],'final_known':result['passes'][-1]['known_source_tokens'],
        'final_new_agents':len(result['passes'][-1]['new_word_agents']),'cards_restored':result['observation_cards_restored']}))
if __name__=='__main__':main()
